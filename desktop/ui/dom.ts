interface GestureEvent extends MouseEvent { scale: number }
declare global {
  interface HTMLElementEventMap { gesturestart: GestureEvent; gesturechange: GestureEvent; gestureend: GestureEvent }
  interface DocumentEventMap { gestureend: GestureEvent }
}
