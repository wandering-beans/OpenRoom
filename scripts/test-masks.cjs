const assert = require('node:assert/strict');

module.exports = async function testMasks(page, url) {
  await page.setViewportSize({width:1320, height:1000});
  await page.goto(url);
  await page.click('#module-develop');
  await page.waitForFunction(() => document.querySelector('#full-image').src.includes('develop-'));
  await page.fill('#develop-exposure-value', '.5');
  await page.locator('#develop-exposure-value').blur();
  await page.locator('.develop-toolstrip [data-tool="brush"]').click();
  async function checkPalettePosition() {
    const palette = await page.locator('#mask-palette').boundingBox();
    const panel = await page.locator('#develop-panel').boundingBox();
    assert.ok(palette.x >= 0 && palette.x + palette.width <= panel.x + 1, 'mask layers must float to the left of the histogram');
    assert.ok(Math.abs(palette.y - panel.y) < 2, 'mask layers must align with the top of the histogram panel');
    assert.equal(await page.locator('#mask-palette #mask-new, #mask-palette #mask-layers, #mask-palette #mask-overlay').count(), 3);
    assert.equal(await page.locator('#develop-controls #local-exposure').count(), 1, 'correction sliders stay in the right panel');
  }
  await checkPalettePosition();
  assert.equal(await page.locator('#mask-type, #mask-operation, #mask-opacity').count(), 0, 'removed drawing controls must not remain in the UI');
  assert.equal(await page.locator('.develop-scroll').evaluate(node => node.scrollTop), 0, 'opening masks keeps the histogram in view');
  const recipe = () => page.evaluate(() => calls.filter(c => c.command === 'develop_preview').at(-1).args.settings);
  async function create(kind, start, end, count) {
    await page.click('#mask-new');
    assert.deepEqual(await page.locator('[data-mask-type]').allTextContents(), ['ブラシ', '線形グラデーション', '円形グラデーション']);
    await page.locator(`[data-mask-type="${kind}"]`).click();
    assert.equal(await page.locator('#local-exposure').isEnabled(), false);
    const box = await page.locator('#develop-overlay').boundingBox();
    await page.mouse.move(box.x + box.width * start[0], box.y + box.height * start[1]);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * end[0], box.y + box.height * end[1], {steps:8});
    await page.mouse.up();
    await page.waitForFunction(count => document.querySelectorAll('.mask-layer').length === count, count);
    assert.equal(await page.inputValue('#local-exposure-value'), '0', 'new layers must be neutral');
    assert.equal(await page.locator('[data-mask-overlay]').count(), 1);
  }
  async function adjust(key, value) {
    await page.fill(`#local-${key}-value`, String(value));
    await page.locator(`#local-${key}-value`).blur();
    await page.waitForFunction(() => document.querySelector('#develop-status').textContent === '保存済み');
  }
  await create('linear', [.3,.2], [.3,.6], 1);
  await adjust('exposure', 1.25);
  assert.equal((await recipe()).exposure, .5, 'local sliders must leave the global recipe alone');
  await create('radial', [.5,.5], [.8,.8], 2);
  await adjust('exposure', -1);
  await create('brush', [.2,.8], [.8,.7], 3);
  await adjust('texture', 50);
  assert.equal(await page.getAttribute('.develop-toolstrip [data-tool="brush"]', 'aria-pressed'), 'true');
  assert.deepEqual(await page.locator('.mask-layer span').allTextContents(), ['マスク 3', 'マスク 2', 'マスク 1']);
  await page.locator('[data-mask-index="1"]').click();
  assert.equal(await page.inputValue('#local-exposure-value'), '-1');
  assert.equal(await page.inputValue('#local-texture-value'), '0');
  assert.equal(await page.locator('.mask-layer-row:has([data-mask-index="1"]) #mask-enabled').count(), 1);
  assert.equal(await page.locator('.mask-layer-row:has([data-mask-index="1"]) #mask-invert').count(), 1);
  await page.check('#mask-invert');
  await page.waitForFunction(() => document.querySelector('#develop-status').textContent === '保存済み');
  assert.deepEqual((await recipe()).masks.map(mask => mask.invert), [false, true, false]);
  await page.locator('[data-mask-index="0"]').click();
  assert.equal(await page.isChecked('#mask-invert'), false);
  await page.locator('[data-mask-index="1"]').click();
  assert.equal(await page.isChecked('#mask-invert'), true);
  await page.click('#develop-undo');
  assert.equal(await page.isChecked('#mask-invert'), false);
  assert.equal(await page.locator('#develop-exposure').isVisible(), false);
  await page.uncheck('#mask-overlay');
  assert.equal(await page.locator('[data-mask-overlay]').count(), 0);
  await page.check('#mask-overlay');
  await page.click('#mask-up');
  assert.equal(await page.locator('.mask-layer span').first().textContent(), 'マスク 2');
  await page.click('#develop-undo');
  assert.deepEqual(await page.locator('.mask-layer span').allTextContents(), ['マスク 3', 'マスク 2', 'マスク 1']);
  await page.locator('[data-mask-index="1"]').click();
  await page.check('#local-monochrome');
  await page.uncheck('#mask-enabled');
  assert.match(await page.locator('.mask-layer[aria-pressed=true]').textContent(), /無効/);
  await page.click('#develop-undo');
  assert.equal(await page.isChecked('#mask-enabled'), true);
  await page.click('#mask-copy');
  assert.equal(await page.locator('.mask-layer').count(), 4);
  assert.equal(await page.inputValue('#local-exposure-value'), '-1');
  await page.click('#mask-delete');
  assert.equal(await page.locator('.mask-layer').count(), 3);
  await page.click('#develop-undo');
  assert.equal(await page.locator('.mask-layer').count(), 4);
  await page.locator('[data-mask-index="3"]').click();
  await page.click('#mask-reset');
  await page.waitForFunction(() => document.querySelector('#develop-status').textContent === '保存済み');
  const saved = await recipe();
  assert.deepEqual(saved.masks[3].adjustments, {});
  assert.equal(saved.masks[1].adjustments.exposure, -1);
  assert.equal(saved.masks[1].adjustments.monochrome, 1);
  assert.equal(saved.masks[2].adjustments.texture, 50);
  assert.equal(saved.exposure, .5);
  await page.locator('#mask-new').scrollIntoViewIfNeeded();
  await checkPalettePosition();
  if (process.env.AE_UI_SCREENSHOT) await page.screenshot({path:process.env.AE_UI_SCREENSHOT.replace('.png','-masks.png')});
  await page.setViewportSize({width:900, height:740});
  await checkPalettePosition();
  await page.click('#toggle-inspector');
  assert.equal(await page.locator('#mask-palette').isVisible(), false, 'hiding the right panel also hides the mask palette');
  await page.click('#toggle-inspector');
  await checkPalettePosition();
  await page.setViewportSize({width:1320, height:1000});
  await page.click('#mask-done');
  assert.equal(await page.locator('#mask-palette').isVisible(), false);
  assert.equal(await page.locator('#develop-exposure').isVisible(), true);
  assert.equal(await page.locator('#develop-overlay').isVisible(), false);
  await page.click('#module-library'); await page.click('#module-develop');
  await page.waitForFunction(() => document.querySelector('#develop-status').textContent === '保存済み');
  assert.deepEqual((await recipe()).masks, saved.masks, 'layer order and independent adjustments must survive reopening');
  await page.locator('.develop-toolstrip [data-tool="brush"]').click();
  await page.locator('[data-mask-index="1"]').click();
  const callsBeforeDisable = await page.evaluate(() => calls.length);
  await page.uncheck('#mask-enabled');
  await page.waitForFunction(() => document.querySelector('#develop-status').textContent === '保存済み');
  assert.equal(await page.evaluate(start => calls.slice(start).some(call => call.command === 'refresh_library_preview'), callsBeforeDisable), false, 'autosaving a mask must not generate library previews during editing');
  await page.evaluate(() => { window.failLibraryRefresh = true; });
  await page.click('#module-library');
  await page.waitForFunction(() => document.querySelector('#error').textContent.includes('Injected library refresh failure'));
  assert.equal(await page.locator('#module-develop').getAttribute('aria-current'), 'page', 'failed refresh must keep the current development visible');
  assert.equal(await page.isChecked('#mask-enabled'), false);
  assert.equal(await page.locator('#app-shell').evaluate(shell => shell.inert), false, 'failed refresh must allow retry');
  await page.evaluate(() => { window.failLibraryRefresh = false; });
  await page.click('#module-library');
  const disabledSave = await page.evaluate(() => calls.filter(call => call.command === 'save_develop').at(-1));
  assert.equal(disabledSave.args.settings.masks[1].enabled, false);
  const revision = disabledSave.args.expectedRevision + 1;
  await page.waitForFunction(({id, revision}) => document.querySelector('#full-image').src.includes(`preview-${id}-1600-r${revision}`), {id:disabledSave.args.id, revision});
  assert.equal(await page.locator('#module-library').getAttribute('aria-current'), 'page');
  await page.click('#module-develop');
  await page.waitForFunction(() => document.querySelector('#develop-status').textContent === '保存済み');
  assert.equal((await recipe()).masks[1].enabled, false, 'disabled masks must stay disabled after a library round trip');
  console.log('Mask layers: three shapes, neutral creation, shared sliders, overlay, reorder, copy/delete, undo and reopen passed.');
};
