const assert = require('node:assert/strict');
const close = (actual, expected, message, tolerance = 1) => assert.ok(Math.abs(actual - expected) < tolerance, `${message}: ${actual} != ${expected}`);

module.exports = async function testCropPan(page, url) {
  await page.goto(url);
  await page.click('#module-develop');
  await page.waitForFunction(() => document.querySelector('#full-image').src.includes('develop-1-0-1600'));
  await page.locator('[data-tool="crop"]').click();
  await page.selectOption('#crop-ratio', '0');
  const overlay = page.locator('#develop-overlay');
  const photo = page.locator('#full-image');
  const frame = page.locator('#develop-overlay > rect').first();
  const original = await overlay.boundingBox();
  await page.mouse.move(original.x + original.width * .2, original.y + original.height * .2);
  await page.mouse.down();
  await page.mouse.move(original.x + original.width * .7, original.y + original.height * .7, {steps:4});
  await page.mouse.up();
  async function savedCrop() {
    await page.waitForFunction(() => document.querySelector('#develop-status').textContent === '保存済み');
    return page.evaluate(() => calls.filter(c => c.command === 'save_develop').at(-1).args.settings.crop);
  }
  await savedCrop();
  async function pan(dx, dy) {
    const beforeCrop = await savedCrop();
    const beforePhoto = await photo.boundingBox(), beforeFrame = await frame.boundingBox();
    const start = {x:beforeFrame.x + beforeFrame.width / 2, y:beforeFrame.y + beforeFrame.height / 2};
    await page.mouse.move(start.x, start.y);
    assert.equal(await overlay.evaluate(node => node.style.cursor), 'grab');
    await page.mouse.down();
    await page.mouse.move(start.x + dx, start.y + dy, {steps:5});
    const nextX = Math.max(0, Math.min(1-beforeCrop[2], beforeCrop[0]-dx/beforePhoto.width));
    const nextY = Math.max(0, Math.min(1-beforeCrop[3], beforeCrop[1]-dy/beforePhoto.height));
    const duringPhoto = await photo.boundingBox(), duringFrame = await frame.boundingBox();
    close(duringPhoto.x-beforePhoto.x, (beforeCrop[0]-nextX)*beforePhoto.width, 'photo follows horizontal drag');
    close(duringPhoto.y-beforePhoto.y, (beforeCrop[1]-nextY)*beforePhoto.height, 'photo follows vertical drag');
    for (const key of ['x','y','width','height']) close(duringFrame[key], beforeFrame[key], `crop frame retains ${key}`);
    await page.mouse.up();
    const after = await savedCrop(), afterFrame = await frame.boundingBox();
    for (const key of ['x','y','width','height']) close(afterFrame[key], beforeFrame[key], `release retains frame ${key}`);
    for (const [index, expected] of [nextX,nextY,beforeCrop[2],beforeCrop[3]].entries()) close(after[index], expected, 'saved crop matches visible composition', 1e-6);
  }
  await pan(40, 30);
  await pan(-20, -15);
  await pan(original.width, original.height);
  const beforeCancel = await photo.boundingBox(), savedBeforeCancel = await savedCrop();
  const cropFrame = await frame.boundingBox();
  await page.mouse.move(cropFrame.x+cropFrame.width/2, cropFrame.y+cropFrame.height/2);
  await page.mouse.down();
  await page.mouse.move(cropFrame.x+cropFrame.width/2-25, cropFrame.y+cropFrame.height/2-25);
  await overlay.dispatchEvent('pointercancel');
  await page.mouse.up();
  const afterCancel = await photo.boundingBox();
  close(afterCancel.x, beforeCancel.x, 'cancel restores image position');
  close(afterCancel.y, beforeCancel.y, 'cancel restores image position');
  assert.deepEqual(await savedCrop(), savedBeforeCancel);
  await page.click('#zoom-in');
  await page.waitForFunction(() => document.querySelector('#full-image').src.endsWith('-0'));
  await pan(-20, -20);
  await page.click('#toggle-sidebar');
  await page.click('#navigator-fit');
  await page.waitForFunction(() => { const photo=document.getElementById('full-image').getBoundingClientRect(), overlay=document.getElementById('develop-overlay').getBoundingClientRect(); return Math.abs(photo.x-overlay.x)<1 && Math.abs(photo.y-overlay.y)<1 && Math.abs(photo.width-overlay.width)<1 && Math.abs(photo.height-overlay.height)<1; });
  const beforeResize = await savedCrop();
  const corner = await page.locator('[data-crop-corner="se"]').boundingBox();
  await page.mouse.move(corner.x+corner.width/2, corner.y+corner.height/2);
  await page.mouse.down();
  await page.mouse.move(corner.x+corner.width/2-20, corner.y+corner.height/2-20, {steps:3});
  await page.mouse.up();
  const resized = await savedCrop();
  close(resized[0], beforeResize[0], 'resizing keeps opposite corner x', 1e-6);
  close(resized[1], beforeResize[1], 'resizing keeps opposite corner y', 1e-6);
  assert.ok(resized[2] < beforeResize[2] && resized[3] < beforeResize[3], `corner drag still resizes after panning: ${JSON.stringify({beforeResize,resized,corner,photo:await photo.boundingBox(),overlay:await overlay.boundingBox(),zoom:await page.textContent('#zoom-level'),viewport:page.viewportSize()})}`);
  await pan(10, 10);
  const finalCrop = await savedCrop();
  await page.keyboard.press('Enter');
  assert.equal(await overlay.isVisible(), false);
  assert.equal(await photo.evaluate(node => node.style.translate), '', 'finishing must clear temporary photo translation');
  await page.waitForFunction(crop => JSON.stringify(calls.filter(c=>c.command==='develop_preview').at(-1).args.settings.crop) === JSON.stringify(crop), finalCrop);
  await page.click('#film-next');
  await page.waitForFunction(() => document.querySelector('#full-image').src.includes('develop-2-'));
  assert.equal(await photo.evaluate(node => node.style.translate), '', 'photo navigation must not inherit translation');
  console.log('Crop photo pan: direction, stationary frame, repeated drags, image bounds, cancellation, zoom, resizing, Enter and navigation passed.');
};
