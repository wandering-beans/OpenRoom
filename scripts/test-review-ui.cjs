const assert = require('node:assert/strict');
module.exports = async function testReview(page) {
  const card = id => page.locator(`.review-card[data-id="${id}"]`);
  const active = async () => Number(await page.locator('.review-card.active').getAttribute('data-id'));
  const selected = async () => page.evaluate(() => [...document.querySelectorAll('.film-tile.selected')].map(tile => Number(tile.querySelector('.film-number').textContent)));
  const loaded = () => page.waitForFunction(() => [...document.querySelectorAll('.review-card img')].length > 0 && [...document.querySelectorAll('.review-card img')].every(image => image.complete && image.naturalWidth > 0));
  await page.keyboard.press('c'); await loaded();
  assert.equal(await page.locator('#compare-view').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('.review-card').count(), 2, 'single selection picks an adjacent comparison photo');
  assert.match(await card(1).locator('.review-heading').textContent(), /^基準/);
  await page.keyboard.press('ArrowRight'); await loaded();
  assert.equal(await card(1).count(), 1, 'candidate navigation keeps the reference');
  assert.equal(await card(3).count(), 1);
  assert.equal(await active(), 3);
  await page.click('#compare-swap');
  assert.match(await card(3).locator('.review-heading').textContent(), /^基準/);
  await page.click('#compare-promote'); await loaded();
  assert.match(await card(1).locator('.review-heading').textContent(), /^基準/);
  assert.equal(await card(2).count(), 1, 'promoting a candidate advances to another photo');
  await card(2).locator('.review-heading').click();
  await page.waitForFunction(() => !document.querySelector('#annotation-rating').disabled);
  await page.click('#photo-flags [data-flag="1"]');
  await page.waitForFunction(() => calls.filter(call => call.command === 'set_photo_attributes').at(-1)?.args.ids[0] === 2);
  assert.deepEqual(await page.evaluate(() => calls.filter(call => call.command === 'set_photo_attributes').at(-1).args.ids), [2], 'review flags affect only the active photo');
  await page.waitForFunction(() => document.querySelector('.review-card[data-id="2"] .review-attributes').textContent.includes('採用'));
  await loaded();
  assert.match(await card(1).locator('.review-heading').textContent(), /^基準/, 'attribute refresh retains reference and candidate set');
  await page.click('#navigator-100');
  await page.waitForFunction(() => [...document.querySelectorAll('.review-card img')].every(image => image.src.includes('1600')));
  await loaded();
  const scales = () => page.locator('.review-card img').evaluateAll(images => images.map(image => image.getBoundingClientRect().width / Number(image.getAttribute('width'))));
  assert.ok((await scales()).every(scale => Math.abs(scale - 1) < .01), 'comparison zoom is linked');
  await card(2).locator('.review-image-area').evaluate(area => {
    area.dispatchEvent(new WheelEvent('wheel', { deltaX:90, deltaY:120, bubbles:true, cancelable:true }));
  });
  const pan = await page.locator('.review-image-area').evaluateAll(areas => areas.map(area => {
    const image = area.querySelector('img');
    return [(area.scrollLeft + area.clientWidth / 2 - image.offsetLeft) / image.offsetWidth, (area.scrollTop + area.clientHeight / 2 - image.offsetTop) / image.offsetHeight];
  }));
  assert.ok(Math.abs(pan[0][0] - pan[1][0]) < .005 && Math.abs(pan[0][1] - pan[1][1]) < .005, 'panning synchronizes the same normalized photo position');
  await page.uncheck('#compare-linked');
  await page.click('#navigator-50');
  assert.ok((await scales()).some(scale => Math.abs(scale - .5) < .01), JSON.stringify(await page.locator('.review-card img').evaluateAll(images=>images.map(image=>({width:image.width,style:image.style.width,box:image.getBoundingClientRect().width})))));
  assert.ok((await scales()).some(scale => Math.abs(scale - 1) < .01), 'unlinked zoom preserves the other photo');
  await page.check('#compare-linked');
  await page.keyboard.press('ArrowRight'); await loaded();
  assert.ok((await scales()).every(scale => Math.abs(scale - .5) < .01), 'a new comparison candidate inherits linked zoom');
  assert.ok(await page.locator('.review-card img').evaluateAll(images => images.every(image => image.src.includes('1600'))), 'linked candidates inherit the same preview resolution');
  await page.click('#navigator-fit');
  await page.keyboard.press('e');
  await page.locator('.film-tile').first().click();
  await page.locator('.film-tile').nth(4).click({modifiers:['Shift']});
  await page.keyboard.press('n'); await loaded();
  assert.equal(await page.locator('.review-card').count(), 5);
  const before = await page.locator('.review-card').allInnerTexts();
  await card(2).locator('button').filter({hasText:'候補から外す'}).click();
  assert.equal(await page.locator('.review-card').count(), 4);
  assert.equal(await card(2).count(), 0);
  assert.equal((await selected()).includes(2), false, 'removal updates filmstrip selection');
  await page.locator('.film-tile').nth(5).click({modifiers:['Control']});
  assert.equal(await page.locator('.review-card').count(), 5, 'filmstrip can add a survey candidate');
  await card(3).locator('.review-heading').click();
  await page.waitForFunction(() => !document.querySelector('#annotation-rating').disabled);
  await page.click('#rating-stars [data-rating="4"]');
  await page.waitForFunction(() => document.querySelector('.review-card[data-id="3"] .review-attributes').textContent.includes('★★★★'));
  assert.equal(await page.locator('.review-card').count(), 5, 'rating does not collapse survey selection');
  await page.click('#toggle-inspector'); await page.fill('#annotation-memo', '未保存の選別メモ');
  await card(4).locator('.review-heading').click();
  await page.locator('#discard-dialog[open]').waitFor();
  await page.click('#discard-dialog button[value="cancel"]');
  assert.equal(await active(), 3, 'unsaved metadata can block review focus changes');
  assert.equal(await page.inputValue('#annotation-memo'), '未保存の選別メモ');
  await page.click('#annotation-save'); await page.waitForFunction(() => !document.querySelector('#annotation-save').disabled);
  await card(4).locator('.review-heading').click();
  assert.equal(await active(), 4);
  await page.click('#toggle-inspector');
  if (process.env.AE_UI_SCREENSHOT) await page.screenshot({path:process.env.AE_UI_SCREENSHOT.replace('.png','-survey.png')});
  await card(4).click({button:'right'});
  await page.click('#photo-export');
  assert.equal(await page.locator('#export-dialog').isVisible(), true);
  assert.match(await page.locator('#export-selection').textContent(), /^5枚/);
  await page.click('#export-close');
  await page.waitForFunction(() => document.activeElement.classList.contains('review-card'));
  await page.keyboard.press('c'); await loaded();
  if (process.env.AE_UI_SCREENSHOT) await page.screenshot({path:process.env.AE_UI_SCREENSHOT.replace('.png','-compare.png')});
  await page.keyboard.press('g');
  assert.equal(await page.locator('#review-view').isVisible(), false);
  assert.equal(await page.locator('#viewport').isVisible(), true);
  assert.ok(before.length === 5);
  const url = page.url();
  await page.goto(url);
  await page.waitForFunction(() => window.listeners['mcp-request'] && !document.querySelector('#app-shell').inert);
  await page.evaluate(() => { window.failReviewPreviewIds = [2]; });
  await page.click('#compare-view');
  await page.waitForFunction(() => document.querySelector('.review-card[data-id="2"] .review-load')?.textContent.includes('Injected review preview failure'));
  await page.evaluate(() => { window.failReviewPreviewIds = []; });
  await card(2).getByText('再読み込み', {exact:true}).click(); await loaded();
  assert.equal(await card(2).locator('.review-load').isVisible(), false, 'failed previews can be retried');
  const originalSize = page.viewportSize();
  await page.setViewportSize({width:900,height:600});
  await page.waitForFunction(() => [...document.querySelectorAll('.review-card')].every(card => card.getBoundingClientRect().right <= innerWidth));
  if (process.env.AE_UI_SCREENSHOT) await page.screenshot({path:process.env.AE_UI_SCREENSHOT.replace('.png','-compare-small.png')});
  await page.setViewportSize(originalSize);
  const result = await page.evaluate(() => dispatchMcp('set_view', {view:'survey'}));
  assert.equal(result.error, null); assert.equal(result.value.view, 'survey');
  const compare = await page.evaluate(() => dispatchMcp('set_view', {view:'compare'}));
  assert.equal(compare.error, null); assert.equal(compare.value.view, 'compare');
  await page.keyboard.press('g');
  await page.click('#filter-tabs [data-mode="text"]');
  await page.fill('#search', 'photo-0000.jpg');
  await page.waitForFunction(() => document.querySelector('#result-count').textContent === '1枚の写真');
  await page.click('#compare-view'); await loaded();
  assert.equal(await page.locator('.review-card').count(), 1, 'one-photo catalogs remain usable');
  assert.equal(await page.locator('#compare-promote').isEnabled(), false);
  await page.keyboard.press('n');
  assert.equal(await card(1).getByText('候補から外す', {exact:true}).isEnabled(), false, 'the last remaining candidate cannot be removed');
  await page.keyboard.press('g');
  await page.click('#filter-tabs [data-mode="text"]');
  await page.fill('#search', 'no-such-review-photo');
  await page.waitForFunction(() => document.querySelector('#result-count').textContent === '0枚の写真');
  await page.click('#compare-view');
  assert.equal(await page.locator('.review-card').count(), 0);
  assert.equal(await page.locator('#empty').isVisible(), true, 'empty searches have the existing recovery message');
  console.log('Library review checks passed: compare navigation, promotion, linked zoom/pan, survey selection/removal, ratings, flags and unsaved guards.');
};
