// Focused update checks use the same built UI and catalog fixture as the desktop suite.
const assert = require('node:assert/strict');
module.exports = async function testUpdates(page, url) {
  const ready = () => page.waitForFunction(() => window.listeners['open-preferences'] && !document.querySelector('#app-shell').inert);
  const preferences = () => page.evaluate(() => window.listeners['open-preferences']({payload:null}));
  const status = text => page.waitForFunction(text => document.querySelector('#update-status').textContent.includes(text), text);
  const count = command => page.evaluate(command => calls.filter(call => call.command === command).length, command);
  await page.goto(url); await ready(); await preferences();
  assert.equal(await page.locator('#app-version').textContent(), 'OpenRoom 0.7.9');
  assert.equal(await count('check_app_update'), 0, 'opening settings must not contact GitHub automatically');
  await page.click('#check-update'); await status('最新');
  assert.equal(await page.locator('#install-update').count(), 0);
  await page.evaluate(() => window.failUpdateCheck = true);
  await page.click('#check-update'); await status('Injected network failure');
  assert.equal(await page.locator('#install-update').count(), 0);
  await page.evaluate(() => {
    window.failUpdateCheck = false;
    window.availableUpdate = {version:'0.8.0',notes:'<script>throw Error("untrusted")</script>\nRelease notes'};
  });
  await page.click('#check-update'); await status('0.8.0');
  assert.equal(await page.locator('#update-notes script').count(), 0, 'release notes are plain text');
  await page.click('#mcp-close');
  await page.click('#module-develop');
  await page.waitForFunction(() => document.querySelector('#full-image').src.includes('develop-'));
  await page.evaluate(() => {
    window.failDevelopSave = true;
    const input = document.querySelector('#develop-exposure-value');
    input.value='1.25'; input.dispatchEvent(new Event('input',{bubbles:true})); input.dispatchEvent(new Event('change',{bubbles:true}));
  });
  await preferences(); await page.click('#install-update'); await status('保存できません');
  assert.equal(await count('install_app_update'), 0, 'failed edit saves must prevent replacement');
  assert.equal(await count('restart_catalog'), 0);
  await page.evaluate(() => { window.failDevelopSave = false; window.holdUpdate = true; window.failUpdateInstall = true; });
  await page.click('#install-update');
  await page.waitForFunction(() => window.releaseUpdate);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#preferences-dialog').isVisible(), true, 'update dialog cannot close during replacement');
  assert.equal(await page.locator('#mcp-close').isDisabled(), true);
  assert.equal(await page.locator('#check-update').isDisabled(), true);
  assert.equal(await page.locator('#app-shell').evaluate(element => element.inert), true);
  await page.evaluate(() => window.listeners['update-progress']({payload:{downloaded:50,total:100}}));
  await status('50%');
  await page.evaluate(() => window.releaseUpdate()); await status('Injected signature failure');
  assert.equal(await count('restart_catalog'), 0, 'verification failure must not restart');
  assert.equal(await page.locator('#app-shell').evaluate(element => element.inert), false);
  await page.evaluate(() => { window.holdUpdate = false; window.failUpdateInstall = false; window.failRestart = true; });
  await page.click('#install-update'); await status('Injected restart failure');
  assert.equal(await page.locator('#install-update').textContent(), '再起動');
  const installs = await count('install_app_update');
  await page.evaluate(() => window.failRestart = false);
  await page.click('#install-update'); await page.waitForFunction(() => calls.filter(c => c.command === 'restart_catalog').length === 2);
  assert.equal(await count('install_app_update'), installs, 'restart retry must not download or replace again');
  const operations = await page.evaluate(() => calls.filter(c => ['save_develop','install_app_update','restart_catalog'].includes(c.command)));
  const firstInstall = operations.findIndex(c => c.command === 'install_app_update');
  assert.equal(operations[firstInstall-1].command, 'save_develop', 'save edits before installation');
  assert.equal(operations[firstInstall-1].args.settings.exposure, 1.25);
  await page.setViewportSize({width:900,height:600});
  assert.equal(await page.locator('#preferences-dialog').evaluate(element => element.scrollWidth <= element.clientWidth), true);
  if (process.env.AE_UPDATE_SCREENSHOT) await page.screenshot({path:process.env.AE_UPDATE_SCREENSHOT});
  await page.evaluate(() => localStorage.setItem('test-language', 'en'));
  await page.reload(); await ready(); await preferences();
  assert.equal(await page.locator('#update-title').textContent(), 'Version and Updates');
  await page.click('#check-update'); await status('up to date');
  console.log('Update UI checks passed: version, network failure, safe notes, save failure, progress, locking, failed installation, restart retry and English labels.');
};
