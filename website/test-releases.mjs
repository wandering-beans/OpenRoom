import assert from 'node:assert/strict';
import {selectDownloads, fetchDownloads} from './releases.mjs';
const base = 'https://github.com/wandering-beans/OpenRoom/releases';
const asset = name => ({name, size:1024, browser_download_url:`${base}/download/v1/${name}`});
const release = (tag, date, names, extra = {}) => ({tag_name:tag, published_at:date, html_url:`${base}/tag/${tag}`, assets:names.map(asset), ...extra});
const mac = release('v1', '2026-10-31T00:00:00Z', ['OpenRoom-1-macos-arm64.zip'], {prerelease:true});
const win = release('v1-windows.1', '2026-11-06T00:00:00Z', ['OpenRoom-1-windows-x64-setup.exe'], {prerelease:true});
assert.equal(selectDownloads([release('mixed', '2026-11-06T00:00:00Z', ['OpenRoom-1-windows-arm64-setup.exe', 'OpenRoom-1-windows-x64-setup.exe'])]).windows.asset.name, 'OpenRoom-1-windows-x64-setup.exe');
assert.deepEqual(selectDownloads([release('32bit', '2026-11-06T00:00:00Z', ['OpenRoom-1-win32-setup.exe'])]), {});
assert.equal(selectDownloads([release('64bit', '2026-11-06T00:00:00Z', ['OpenRoom-1-windows-x86_64-setup.exe'])]).windows.tag, '64bit');
const draft = release('draft', '2026-11-07T00:00:00Z', ['OpenRoom-2-windows-x64-setup.exe'], {draft:true});
let selected = selectDownloads([mac, draft, win]);
assert.equal(selected.windows.tag, 'v1-windows.1');
assert.equal(selected.macos.tag, 'v1');
assert.equal(selected.windows.prerelease, true);
const both = release('v2', '2026-11-08T00:00:00Z', ['OpenRoom-2-windows-x64-setup.exe', 'OpenRoom-2-macos-arm64.app.tar.gz', 'OpenRoom-2-macos-arm64.zip.sig', 'OpenRoom-2-macos-arm64.zip', 'OpenRoom-2-macos-arm64.dmg', 'OpenRoom-2-source.zip']);
selected = selectDownloads([win, mac, both]);
assert.equal(selected.windows.tag, 'v2');
assert.match(selected.macos.asset.name, /\.dmg$/);
const evil = {...win, assets:[{...win.assets[0], browser_download_url:'https://github.com.evil.test/wandering-beans/OpenRoom/releases/download/v1/setup.exe'}]};
assert.deepEqual(selectDownloads([evil]), {});
assert.deepEqual(selectDownloads([{...mac, html_url:'javascript:alert(1)'}]), {});
assert.deepEqual(selectDownloads([]), {});
assert.deepEqual(selectDownloads([null, {}, {...win, published_at:'invalid'}]), {});
assert.throws(() => selectDownloads({}));
let calls = 0;
selected = await fetchDownloads(async () => {
  calls++;
  return new Response(JSON.stringify(calls === 1 ? [win] : [mac]), {headers: calls === 1 ? {link:'<https://api.github.com/repos/wandering-beans/OpenRoom/releases?per_page=100&page=2>; rel="next"'} : {}});
});
assert.equal(calls, 2);
assert.equal(selected.macos.tag, 'v1');
await assert.rejects(fetchDownloads(async () => new Response('', {status:403})));
await assert.rejects(fetchDownloads(async () => new Response('{}')));
await assert.rejects(fetchDownloads(async () => new Response('[]', {headers:{link:'<https://evil.test/>; rel="next"'}})));
console.log('Release selection passed: OS-specific previews, newer combined releases, asset preference, drafts, invalid data, trusted URLs, pagination, API failure.');
